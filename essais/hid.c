int main(void) {
  struct pointeur_hid p;
  int b, dx, dy, x, y;

  VERIFIE(hid_pointeur(SOURIS_QEMU, sizeof SOURIS_QEMU, &p));
  VERIFIE(!p.absolu && p.id == 0 && p.nb_boutons == 3 && p.x.bit == 8 && p.y.bit == 16 && p.molette.bit == 24);
  static const u8 r1[] = {0x01, 0x05, 0xFB, 0x01};
  VERIFIE(hid_lire(&p, r1, 4, &b, &dx, &dy, &x, &y) && b == 1 && dx == 5 && dy == -5);

  VERIFIE(hid_pointeur(TABLETTE_QEMU, sizeof TABLETTE_QEMU, &p));
  VERIFIE(p.absolu && p.x.max == 0x7fff && p.x.bit == 8 && p.y.bit == 24);
  static const u8 r2[] = {0x02, 0xFF, 0x3F, 0x00, 0x40, 0x00};
  VERIFIE(hid_lire(&p, r2, 6, &b, &dx, &dy, &x, &y) && b == 2 && x == 32766 && y == 32768);
  static const u8 r2b[] = {0x00, 0xFF, 0x7F, 0x00, 0x00, 0x00};
  VERIFIE(hid_lire(&p, r2b, 6, &b, &dx, &dy, &x, &y) && x == 65535 && y == 0);

  VERIFIE(hid_pointeur(SOURIS_RECEPTEUR, sizeof SOURIS_RECEPTEUR, &p));
  VERIFIE(p.id == 2 && p.x.bit == 16 && p.x.taille == 12 && p.y.bit == 28 && p.nb_boutons == 3);
  static const u8 r3[] = {0x02, 0x01, 0x00, 0xFD, 0x7F, 0x00, 0x00, 0x00};
  VERIFIE(hid_lire(&p, r3, 8, &b, &dx, &dy, &x, &y) && b == 1 && dx == -3 && dy == 7);
  static const u8 r3b[] = {0x03, 0x01, 0x00};
  VERIFIE(!hid_lire(&p, r3b, 3, &b, &dx, &dy, &x, &y));     /* un autre rapport de l'appareil */

  VERIFIE(hid_pointeur(PAVE, sizeof PAVE, &p));
  VERIFIE(p.pave && p.id == 2 && !p.absolu && p.nb_boutons == 2 && p.x.bit == 8);
  static const u8 r4[] = {0x02, 0x00, 0x0A, 0xF6};
  VERIFIE(hid_lire(&p, r4, 4, &b, &dx, &dy, &x, &y) && b == 0 && dx == 10 && dy == -10);
  static const u8 r4b[] = {0x01, 0x03, 0x10, 0x00, 0x20, 0x00};
  VERIFIE(!hid_lire(&p, r4b, 6, &b, &dx, &dy, &x, &y));     /* rapport du pavé : pas pour la souris */

  VERIFIE(!hid_pointeur(PAVE_SEUL, sizeof PAVE_SEUL, &p) && p.pave);
  VERIFIE(!hid_pointeur(CLAVIER, sizeof CLAVIER, &p) && !p.pave);

  VERIFIE(hid_pointeur(PILE, sizeof PILE, &p));
  VERIFIE(p.nb_boutons == 1 && p.bit_bouton[0] == 7 && p.x.bit == 8 && p.y.bit == 16);

  VERIFIE(!hid_pointeur(SOURIS_QEMU, 20, &p));               /* descripteur coupé : rien d'inventé */

  if (echecs) { printf("lecteur HID : %d échec(s)\n", echecs); return 1; }
  printf("lecteur HID : tous les essais passent\n");
  return 0;
}
